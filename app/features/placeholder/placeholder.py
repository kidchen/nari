"""Module A: monthly parking PLACEHOLDER image.

Deliberately not a replica of any vendor's receipt: no operator branding, no card digits,
no transaction number, and a permanent "NOT A RECEIPT" watermark. It is a reminder /
stand-in document only — download the real receipt from the parking provider.
"""
from __future__ import annotations

import calendar
import io
from datetime import date, datetime

from PIL import Image, ImageDraw, ImageFont

W, H = 1080, 1350
BG, FG, ACCENT, MUTED, WARN = "#1E1E1E", "#F2F2F2", "#C77DFF", "#9A9A9A", "#FF6B6B"
FONT_PATHS = [
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    "/System/Library/Fonts/Supplemental/Arial.ttf",
]
BOLD_PATHS = [
    "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
    "/System/Library/Fonts/Supplemental/Arial Bold.ttf",
]


def _font(size: int, bold: bool = False) -> ImageFont.FreeTypeFont | ImageFont.ImageFont:
    for p in BOLD_PATHS if bold else FONT_PATHS:
        try:
            return ImageFont.truetype(p, size)
        except OSError:
            continue
    return ImageFont.load_default(size=size)


def period_for(month_start: date) -> tuple[date, date]:
    last = calendar.monthrange(month_start.year, month_start.month)[1]
    return month_start.replace(day=1), month_start.replace(day=last)


def render(month: date, label: str, amount: str, generated_at: datetime | None = None) -> bytes:
    start, end = period_for(month)
    generated_at = generated_at or datetime.now()
    img = Image.new("RGB", (W, H), BG)
    d = ImageDraw.Draw(img)

    d.rectangle([0, 0, W, 150], fill="#2A2A2A")
    d.text((60, 45), "PLACEHOLDER", font=_font(56, bold=True), fill=WARN)
    d.text((W - 60, 62), "not a receipt", font=_font(34), fill=MUTED, anchor="ra")

    d.text((60, 210), label, font=_font(46, bold=True), fill=FG)
    d.text((60, 275), f"{start:%B %Y}", font=_font(36), fill=ACCENT)

    rows = [
        ("Period start", f"{start:%Y/%m/%d}"),
        ("Period end", f"{end:%Y/%m/%d}"),
        ("Expected amount", amount),
        ("Status", "Real receipt still needed"),
    ]
    y = 380
    for k, v in rows:
        d.text((60, y), k, font=_font(30), fill=MUTED)
        d.text((W - 60, y), v, font=_font(34, bold=True), fill=FG, anchor="ra")
        y += 50
        d.line([60, y + 20, W - 60, y + 20], fill="#3A3A3A", width=2)
        y += 55

    note = ["Stand-in document generated by the Nari home automation bot.",
            "Not issued by any parking operator. Not valid for reimbursement.",
            "Download the official receipt from your parking provider account."]
    y += 30
    for line in note:
        d.text((60, y), line, font=_font(26), fill=MUTED)
        y += 40

    # Diagonal watermark across the whole image
    wm = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    wd = ImageDraw.Draw(wm)
    for i, yy in enumerate(range(-200, H + 200, 320)):
        wd.text((W // 2 + (i % 2) * 120, yy), "PLACEHOLDER · NOT A RECEIPT",
                font=_font(64, bold=True), fill=(255, 107, 107, 55), anchor="mm")
    wm = wm.rotate(30, center=(W // 2, H // 2))
    img = Image.alpha_composite(img.convert("RGBA"), wm).convert("RGB")

    d = ImageDraw.Draw(img)
    d.text((60, H - 70), f"Generated {generated_at:%Y-%m-%d %H:%M}", font=_font(24), fill=MUTED)

    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()
